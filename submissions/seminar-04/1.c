#include <stdio.h>

// 1.1
// Правильные: а, в, г, и, л, м, о.
// При этом указатели p и q нужно сначала куда-то направить,
// иначе их разыменовывать нельзя.

// 1.2
// p и q указывают на одно место, поэтому их адреса совпадут.
// a станет равно 3.
// Адрес заранее узнать нельзя.

int main(void) {
    int a, b;
    scanf("%d %d", &a, &b);

    int* a_ptr = &a;
    int* b_ptr = &b;

    int t = *a_ptr;
    *a_ptr = *b_ptr;
    *b_ptr = t;

    printf("%d %d\n", a, b);
    return 0;
}
