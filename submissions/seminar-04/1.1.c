// int x, *p, **q;
// Верно: а, в, г, и, л, м, о

*p;       // а) ок: int
*x;       // б) нет: x не указатель
p = &x;   // в) ок: оба int*
&p;       // г) ок: дает int**
&(&x);    // д) нет: нельзя взять адрес от адреса
x = p;    // е) нет: в int нельзя записать int*
p = x;    // ж) нет: в int* нельзя записать int
q = &x;   // з) нет: q ждет int**, а тут int*
q = &p;   // и) ок: оба int**
**p;      // к) нет: лишняя *
*q;       // л) ок: дает int*
**q;      // м) ок: дает int
***q;     // н) нет: лишняя *
&*p;      // о) ок: & и * гасят друг друга
