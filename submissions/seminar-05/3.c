/*В некотором целочисленном массиве 16 элементов. Известно, что переменная int *p указывает на элемент с индексом 5 данного массива. Напишите цикл for, который обнулит данный массив*/

#include <stdio.h>

int main(void) {
    int a[16];
    int *p = &a[5]; 
    
    for (int i=-5; i<11; i++) {
        p[i] = 0;
    }

    for (int i = 0; i < 16; i++) {
        printf("%d", a[i]);
    }

    printf("\n");
    return 0;

}