// В некотором целочисленном массиве 16 элементов.
// Известно, что переменная int *p указывает на элемент с индексом 5 данного массива.
// Напишите цикл for, который обнулит данный массив
int main(void){
    int arr[16];
    int *p = &arr[5];

    for (int i = 0; i <= 5; i++) {
        *(p - i) = 0;
    }

    for (int i = 1; i < 11; i++) {
        *(p + i) = 0;
    }
    return 0;
}